import assert from 'node:assert/strict';
import fs from 'node:fs';
import ts from 'typescript';
import * as T from 'three';
fs.mkdirSync('work/perf',{recursive:true});
fs.writeFileSync('work/perf/render-batching.mjs',ts.transpileModule(fs.readFileSync('app/render-batching.ts','utf8'),{compilerOptions:{module:ts.ModuleKind.ES2022,target:ts.ScriptTarget.ES2022}}).outputText);
const {batchStaticMeshes}=await import('../work/perf/render-batching.mjs');
const scene=new T.Scene(),seat=new T.Group(),moving=new T.Group(),hidden=new T.Group();
seat.userData.seat='bench';seat.position.set(2,0,1);seat.rotation.y=.4;scene.add(seat,moving,hidden);hidden.visible=false;
const mat=new T.MeshStandardMaterial(),shared=new T.BoxGeometry(.4,.4,.4);
const add=(parent,x,geometry=shared,material=mat)=>{const m=new T.Mesh(geometry,material);m.position.set(x,.5,0);m.castShadow=m.receiveShadow=true;parent.add(m);return m;};
add(seat,-.5);add(seat,.5,new T.BoxGeometry(.4,.4,.4).toNonIndexed());
const animated=add(moving,4);add(hidden,6);
const glass=add(seat,2,shared,new T.MeshStandardMaterial({transparent:true,opacity:.3}));
const noShadow=add(seat,3);noShadow.castShadow=false;
let sharedDisposed=false;shared.addEventListener('dispose',()=>{sharedDisposed=true;});
scene.updateMatrixWorld(true);
const boundsBefore=new T.Box3().setFromObject(seat);
const target=seat.localToWorld(new T.Vector3(-.5,.5,0));
const ray=new T.Raycaster(target.clone().add(new T.Vector3(0,3,0)),new T.Vector3(0,-1,0));
const hitBefore=ray.intersectObject(seat,true)[0];
const stats=batchStaticMeshes(scene,new Set([moving]));scene.updateMatrixWorld(true);
assert.equal(stats.savedDraws,1);assert.equal(moving.children[0],animated);assert.equal(hidden.children.length,1);
assert.equal(glass.parent,seat);assert.equal(noShadow.parent,seat);assert.equal(sharedDisposed,false);
const boundsAfter=new T.Box3().setFromObject(seat);assert(boundsBefore.min.distanceTo(boundsAfter.min)<1e-6);assert(boundsBefore.max.distanceTo(boundsAfter.max)<1e-6);
const hitAfter=ray.intersectObject(seat,true)[0];assert(hitBefore.point.distanceTo(hitAfter.point)<1e-6);assert.equal(hitAfter.object.parent.userData.seat,'bench');
moving.position.x+=2;scene.updateMatrixWorld(true);assert.equal(animated.getWorldPosition(new T.Vector3()).x,6);
console.log('PASS: batching preserves transformed geometry, seat picking, shadow flags, transparent and hidden objects, animation and shared geometry ownership.');
